def _runtime_payload() -> bytes:
    payload = base64.b64decode(EMBEDDED_RUNTIME_BASE64)
    actual = hashlib.sha256(payload).hexdigest()
    if actual != EMBEDDED_RUNTIME_SHA256:
        raise RuntimeError("内嵌周报 Runner 校验失败，脚本可能已损坏")
    return payload


def _extract_runtime(destination: Path) -> None:
    with zipfile.ZipFile(io.BytesIO(_runtime_payload())) as archive:
        for member in archive.infolist():
            path = Path(member.filename)
            if path.is_absolute() or ".." in path.parts:
                raise RuntimeError(f"内嵌 Runner 包含不安全路径: {member.filename}")
        archive.extractall(destination)


def _load_embedded_launcher(runtime_root: Path) -> ModuleType:
    scripts_root = runtime_root / "scripts"
    launcher_path = scripts_root / "run_weekly.py"
    sys.path.insert(0, str(scripts_root))
    spec = importlib.util.spec_from_file_location(
        "standalone_embedded_weekly_launcher", launcher_path
    )
    if spec is None or spec.loader is None:
        raise RuntimeError("无法加载内嵌周报 Runner")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _normalize_targets(values: list[str]) -> list[str]:
    targets: list[str] = []
    for value in values:
        targets.extend(
            item.lower()
            for item in re.split(r"[,，\s]+", value.strip())
            if item.strip()
        )
    return list(dict.fromkeys(targets))


def _resolve_task_id(project_root: Path, target: str) -> str:
    try:
        person, week = TARGETS[target]
    except KeyError as exc:
        supported = " ".join(TARGETS)
        raise ValueError(f"未知 target {target!r}；可用值: {supported}") from exc

    person_root = project_root / "task" / person
    if not person_root.is_dir():
        raise ValueError(f"找不到人员任务目录: {person_root}")

    week_label = WEEK_LABELS[week]
    matches: list[tuple[str, Path]] = []
    for metadata_path in person_root.glob("*/metadata.json"):
        loaded = json.loads(metadata_path.read_text(encoding="utf-8"))
        explicit_target = str(loaded.get("mock_target") or "").strip().lower()
        task_text = str(loaded.get("task") or "")
        configured_week = loaded.get("mock_week")
        if explicit_target:
            selected = explicit_target == target
        else:
            selected = week_label in task_text or str(configured_week) == str(week)
        if not selected:
            continue
        task_id = str(loaded.get("absolute_id") or "").strip()
        if task_id:
            matches.append((task_id, metadata_path))

    if not matches:
        raise ValueError(f"未找到 {target} 对应的 {person}{week_label} metadata")
    if len(matches) > 1:
        paths = ", ".join(str(path) for _, path in matches)
        raise ValueError(f"{target} 对应的 metadata 不唯一: {paths}")
    return matches[0][0]


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="按 c1/c2 等 note target 串行执行小艺周报 Runner"
    )
    parser.add_argument(
        "targets",
        nargs="*",
        help="一个或多个 note target，例如 c1 c2 f1；也支持逗号分隔",
    )
    parser.add_argument(
        "--project-root",
        default=str(SCRIPT_ROOT),
        help="包含 task/ 和 deliverables_final/ 的数据根目录；默认也从这里找 note/",
    )
    parser.add_argument("--agent-workspace", help="批次产物输出根目录")
    parser.add_argument(
        "--note-root",
        help="note 目录，内部需包含 data_yangshi/jiaoben/run_data_mock.py",
    )
    parser.add_argument("--mock-runner-script", help="自定义 run_data_mock.py")
    parser.add_argument("--config", help="自定义周报 Runner 配置")
    parser.add_argument("--device", help="HDC 目标设备 ID")
    parser.add_argument("--date", help="运行日期 YYYYMMDD")
    parser.add_argument("--dry-run", action="store_true", help="只预演，不操作 HDC")
    parser.add_argument("--rerun", action="store_true", help="覆盖已完成的任务")
    parser.add_argument("--stop-on-error", action="store_true")
    parser.add_argument("--verbose", "-v", action="store_true")
    parser.add_argument(
        "--list-targets", action="store_true", help="列出 target 映射后退出"
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)
    if args.list_targets:
        for target, (person, week) in TARGETS.items():
            print(f"{target}: {person}{WEEK_LABELS[week]}")
        return 0

    targets = _normalize_targets(args.targets)
    if not targets:
        parser.error("请至少指定一个 target，例如: c1 c2")

    project_root = Path(args.project_root).expanduser().resolve()
    if args.mock_runner_script:
        mock_runner_script = Path(args.mock_runner_script).expanduser().resolve()
    else:
        note_root = (
            Path(args.note_root).expanduser().resolve()
            if args.note_root
            else project_root / "note"
        )
        mock_runner_script = (
            note_root / "data_yangshi" / "jiaoben" / "run_data_mock.py"
        )
    try:
        selections = [
            (target, _resolve_task_id(project_root, target)) for target in targets
        ]
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        parser.error(str(exc))
    if not mock_runner_script.is_file():
        parser.error(f"找不到 note 数据入口: {mock_runner_script}")

    forwarded = [
        "--project-root", str(project_root),
        "--mock-runner-script", str(mock_runner_script),
    ]
    for name in ("agent_workspace", "config", "device", "date"):
        value = getattr(args, name)
        if value:
            forwarded.extend([f"--{name.replace('_', '-')}", value])
    for flag in ("dry_run", "rerun", "stop_on_error", "verbose"):
        if getattr(args, flag):
            forwarded.append(f"--{flag.replace('_', '-')}")
    for target, task_id in selections:
        person, week = TARGETS[target]
        print(f"[selection] {target} -> {person}{WEEK_LABELS[week]} -> Task {task_id}")
        forwarded.extend(["--task", task_id])

    with tempfile.TemporaryDirectory(prefix="xiaoyi-weekly-standalone-") as temp_dir:
        runtime_root = Path(temp_dir)
        _extract_runtime(runtime_root)
        launcher = _load_embedded_launcher(runtime_root)
        return int(launcher.main(forwarded))


if __name__ == "__main__":
    raise SystemExit(main())
